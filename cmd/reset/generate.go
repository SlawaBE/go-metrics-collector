package main

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
)

// typeInfo describes a type declared in the scanned package.
type typeInfo struct {
	spec     *ast.TypeSpec
	name     string
	base     string
	pos      token.Pos
	isStruct bool
	hasReset bool // an explicit Reset method already exists in the package
	genReset bool // the type carries the // generate:reset directive
}

// packageModel holds everything collected while scanning a single package
// directory.
type packageModel struct {
	fset    *token.FileSet
	dir     string
	pkgName string
	types   map[string]*typeInfo
	structs []*typeInfo // structs with genReset, in declaration order
}

// skipScanDir reports whether a directory should not be walked.
func skipScanDir(name string) bool {
	if name == "testdata" || name == ".git" {
		return true
	}
	if strings.HasPrefix(name, ".") {
		return true
	}
	return false
}

// generatedFile reports whether the file was produced by this or another code
// generator, in which case it must not be re-analyzed.
func generatedFile(src []byte) bool {
	for _, line := range strings.Split(string(src), "\n") {
		line = strings.TrimSpace(line)
		if strings.HasPrefix(line, "//") && strings.Contains(line, "Code generated") && strings.Contains(line, "DO NOT EDIT") {
			return true
		}
	}
	return false
}

// processDir scans a single directory, parses its non-generated source files
// and writes the reset.gen.go file when the package contains structs marked
// with // generate:reset.
func processDir(dir string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}

	fset := token.NewFileSet()
	pm := &packageModel{
		fset:  fset,
		dir:   dir,
		types: make(map[string]*typeInfo),
	}

	var files []*ast.File
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		name := entry.Name()
		if !strings.HasSuffix(name, ".go") {
			continue
		}
		if strings.HasSuffix(name, "_test.go") || name == "reset.gen.go" {
			continue
		}
		path := filepath.Join(dir, name)
		src, readErr := os.ReadFile(path)
		if readErr != nil {
			return readErr
		}
		if generatedFile(src) {
			continue
		}
		f, parseErr := parser.ParseFile(fset, path, src, parser.ParseComments)
		if parseErr != nil {
			return fmt.Errorf("%s: %w", path, parseErr)
		}
		files = append(files, f)
	}

	if len(files) == 0 {
		return nil
	}
	pm.pkgName = files[0].Name.Name

	collectPackage(pm, files)
	if len(pm.structs) == 0 {
		return nil
	}

	content, err := generateFile(pm)
	if err != nil {
		return fmt.Errorf("package %s (%s): %w", pm.pkgName, dir, err)
	}
	return writeFile(dir, "reset.gen.go", content)
}

// collectPackage fills the model from the parsed AST of a package: it
// registers declared types and their Reset methods, and marks structs carrying
// the // generate:reset directive.
func collectPackage(pm *packageModel, files []*ast.File) {
	for _, f := range files {
		for _, decl := range f.Decls {
			switch d := decl.(type) {
			case *ast.GenDecl:
				for _, spec := range d.Specs {
					ts, ok := spec.(*ast.TypeSpec)
					if !ok {
						continue
					}
					ti := &typeInfo{name: ts.Name.Name, spec: ts, pos: ts.Pos()}
					switch ts.Type.(type) {
					case *ast.StructType:
						ti.isStruct = true
					}
					if ident, ok := ts.Type.(*ast.Ident); ok && isBasic(ident.Name) {
						ti.base = ident.Name
					}
					if markerDoc(ts.Doc, d.Doc) {
						ti.genReset = true
						if ti.isStruct {
							pm.structs = append(pm.structs, ti)
						}
					}
					pm.types[ti.name] = ti
				}
			case *ast.FuncDecl:
				if d.Name.Name != "Reset" || d.Recv == nil {
					continue
				}
				recv := d.Recv.List
				if len(recv) != 1 {
					continue
				}
				typ := recv[0].Type
				if star, ok := typ.(*ast.StarExpr); ok {
					typ = star.X
				}
				if id, ok := typ.(*ast.Ident); ok {
					if ti, ok := pm.types[id.Name]; ok {
						ti.hasReset = true
					}
				}
			}
		}
	}
}

// generateFile builds the whole reset.gen.go content for a package.
func generateFile(pm *packageModel) (string, error) {
	var b strings.Builder

	b.WriteString("// Code generated by cmd/reset; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pm.pkgName)

	for _, ti := range pm.structs {
		body, err := resetMethod(pm, ti)
		if err != nil {
			return "", fmt.Errorf("type %s: %w", ti.name, err)
		}
		b.WriteString(body)
		b.WriteString("\n")
	}
	return b.String(), nil
}

// resetMethod produces the full Reset method source for a struct.
func resetMethod(pm *packageModel, ti *typeInfo) (string, error) {
	st, ok := ti.spec.Type.(*ast.StructType)
	if !ok {
		return "", fmt.Errorf("generate:reset struct not found: %s", ti.name)
	}

	var body []string
	body = append(body, "if rs == nil {", "\treturn", "}", "")

	for _, field := range st.Fields.List {
		lines, err := fieldReset(pm, field)
		if err != nil {
			return "", fmt.Errorf("field %s at %s: %w", fieldName(field), position(pm, field.Pos()), err)
		}
		body = append(body, lines...)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Reset zeroes the receiver struct fields back to their initial values.\n")
	fmt.Fprintf(&b, "func (rs *%s) Reset() {\n", ti.name)
	for _, line := range body {
		if line == "" {
			b.WriteString("\n")
			continue
		}
		b.WriteString("\t" + line + "\n")
	}
	b.WriteString("}\n")
	return b.String(), nil
}

// fieldReset produces the reset statements for a single struct field.
func fieldReset(pm *packageModel, field *ast.Field) ([]string, error) {
	if len(field.Names) == 0 {
		// Embedded field: refer to it by its type name.
		name := embeddedFieldName(field.Type)
		if name == "" {
			return nil, fmt.Errorf("unsupported embedded field type")
		}
		return valueResetLines(pm, "rs."+name, field.Type)
	}
	name := field.Names[0].Name
	return valueResetLines(pm, "rs."+name, field.Type)
}

// embeddedFieldName returns the type name of an embedded field, or "" when the
// embedded type is not a plain identifier.
func embeddedFieldName(typ ast.Expr) string {
	switch t := typ.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.StarExpr:
		if id, ok := t.X.(*ast.Ident); ok {
			return id.Name
		}
	}
	return ""
}

// valueResetLines returns the statements resetting the value addressed by
// expr, whose type is typ.
func valueResetLines(pm *packageModel, expr string, typ ast.Expr) ([]string, error) {
	switch t := typ.(type) {
	case *ast.Ident:
		return identResetLines(pm, expr, t)
	case *ast.StarExpr:
		return pointerResetLines(pm, expr, t)
	case *ast.ArrayType:
		if t.Len == nil {
			// Slice: truncate, do not nil out.
			return []string{expr + " = " + expr + "[:0]"}, nil
		}
		return nil, fmt.Errorf("fixed-size arrays are not supported")
	case *ast.MapType:
		return []string{"clear(" + expr + ")"}, nil
	case *ast.SelectorExpr:
		return nil, fmt.Errorf("external type %s is not supported (resetter targets data-only structs)", exprType(typ))
	case *ast.ChanType, *ast.FuncType, *ast.InterfaceType:
		return nil, fmt.Errorf("type %s is not supported (resetter targets data-only structs)", exprType(typ))
	default:
		return nil, fmt.Errorf("unsupported type %s", exprType(typ))
	}
}

// identResetLines handles a plain identifier type (basic, named basic, or a
// struct declared in the same package).
func identResetLines(pm *packageModel, expr string, id *ast.Ident) ([]string, error) {
	if zero, ok := zeroOf(id.Name); ok {
		return []string{expr + " = " + zero}, nil
	}
	ti, ok := pm.types[id.Name]
	if !ok {
		return nil, fmt.Errorf("type %s is not declared in this package", id.Name)
	}
	if ti.isStruct {
		if ti.hasReset || ti.genReset {
			return []string{expr + ".Reset()"}, nil
		}
		return nil, fmt.Errorf("nested struct %s has no Reset() and is not marked with // generate:reset", id.Name)
	}
	if zero, ok := zeroOf(ti.base); ok {
		return []string{expr + " = " + zero}, nil
	}
	return nil, fmt.Errorf("unsupported identifier type %s", id.Name)
}

// pointerResetLines resets the value behind a non-nil pointer.
func pointerResetLines(pm *packageModel, expr string, ptr *ast.StarExpr) ([]string, error) {
	inner, err := pointerTarget(pm, "*"+expr, ptr.X)
	if err != nil {
		return nil, err
	}
	out := []string{"if " + expr + " != nil {"}
	out = append(out, indent(inner, 1)...)
	out = append(out, "}")
	return out, nil
}

// pointerTarget returns the statements resetting the value referenced by
// expr (an arbitrary address expression), whose element type is elem.
func pointerTarget(pm *packageModel, expr string, elem ast.Expr) ([]string, error) {
	switch t := elem.(type) {
	case *ast.Ident:
		if zero, ok := zeroOf(t.Name); ok {
			return []string{expr + " = " + zero}, nil
		}
		ti, ok := pm.types[t.Name]
		if !ok {
			return nil, fmt.Errorf("type %s is not declared in this package", t.Name)
		}
		if ti.isStruct {
			if ti.hasReset || ti.genReset {
				// elem is the struct name; the pointee expression is the field
				// itself, not *field.
				pointee := strings.TrimPrefix(expr, "*")
				return []string{pointee + ".Reset()"}, nil
			}
			return nil, fmt.Errorf("nested struct %s has no Reset() and is not marked with // generate:reset", t.Name)
		}
		if zero, ok := zeroOf(ti.base); ok {
			return []string{expr + " = " + zero}, nil
		}
		return nil, fmt.Errorf("unsupported identifier type %s", t.Name)
	case *ast.StarExpr:
		return pointerResetLines(pm, expr, t)
	case *ast.ArrayType:
		if t.Len == nil {
			return []string{expr + " = (" + expr + ")[:0]"}, nil
		}
		return nil, fmt.Errorf("fixed-size arrays are not supported")
	case *ast.MapType:
		return []string{"clear(" + expr + ")"}, nil
	default:
		return nil, fmt.Errorf("unsupported pointer target type %s", exprType(elem))
	}
}

// zeroOf returns the zero value literal for a built-in basic type name.
func zeroOf(name string) (string, bool) {
	switch name {
	case "string":
		return `""`, true
	case "bool":
		return "false", true
	case "int", "int8", "int16", "int32", "int64",
		"uint", "uint8", "uint16", "uint32", "uint64", "uintptr",
		"byte", "rune", "float32", "float64", "complex64", "complex128":
		return "0", true
	}
	return "", false
}

func isBasic(name string) bool {
	_, ok := zeroOf(name)
	return ok
}

// markerDoc reports whether any of the given comment groups carries the
// // generate:reset directive.
func markerDoc(docs ...*ast.CommentGroup) bool {
	for _, d := range docs {
		if d != nil && strings.Contains(d.Text(), "generate:reset") {
			return true
		}
	}
	return false
}

// indent adds n leading tabs to each non-empty line.
func indent(lines []string, n int) []string {
	out := make([]string, 0, len(lines))
	tab := strings.Repeat("\t", n)
	for _, l := range lines {
		if l == "" {
			out = append(out, "")
			continue
		}
		out = append(out, tab+l)
	}
	return out
}

// fieldName returns a readable field name for error messages.
func fieldName(field *ast.Field) string {
	if len(field.Names) == 0 {
		return embeddedFieldName(field.Type)
	}
	return field.Names[0].Name
}

// exprType renders a type expression for error messages.
func exprType(typ ast.Expr) string {
	switch t := typ.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.StarExpr:
		return "*" + exprType(t.X)
	case *ast.SelectorExpr:
		return t.Sel.Name
	case *ast.ArrayType:
		if t.Len == nil {
			return "[]" + exprType(t.Elt)
		}
		return "[" + exprType(t.Len) + "]" + exprType(t.Elt)
	case *ast.MapType:
		return "map[" + exprType(t.Key) + "]" + exprType(t.Value)
	case *ast.ChanType:
		return "<-chan"
	case *ast.FuncType:
		return "func"
	case *ast.InterfaceType:
		return "interface"
	}
	return "unknown"
}

// position renders "file:line:col" for an AST position.
func position(pm *packageModel, pos token.Pos) string {
	p := pm.fset.Position(pos)
	return fmt.Sprintf("%s:%d:%d", p.Filename, p.Line, p.Column)
}

// writeFile writes content into dir/fileName.
func writeFile(dir, fileName, content string) error {
	path := filepath.Join(dir, fileName)
	return os.WriteFile(path, []byte(content), 0o644)
}

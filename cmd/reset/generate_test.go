// writePackage writes the given source as the sole non-generated Go file in a
// temporary package directory and runs generation on it.
func writePackage(t *testing.T, src string) string {
	t.Helper()
	dir := t.TempDir()
	err := os.WriteFile(filepath.Join(dir, "types.go"), []byte(src), 0o644)
	require.NoError(t, err)
	err = processDir(dir)
	require.NoError(t, err)
	return readGenerated(t, dir)
}

// readGenerated returns the content of reset.gen.go, asserting it exists.
func readGenerated(t *testing.T, dir string) string {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(dir, "reset.gen.go"))
	require.NoError(t, err, "reset.gen.go was not generated")
	return strings.TrimSpace(string(data))
}

// assertCompiles type-checks the generated package together with the source
// declarations of its types.
func assertCompiles(t *testing.T, dir string) {
	t.Helper()
	fset := token.NewFileSet()
	var files []*ast.File
	for _, name := range []string{"types.go", "reset.gen.go"} {
		f, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.ParseComments)
		require.NoError(t, err)
		files = append(files, f)
	}
	conf := types.Config{Importer: importer.Default()}
	_, err := conf.Check("sample", fset, files, nil)
	require.NoError(t, err)
}

func TestGenerate_ResetableStruct(t *testing.T) {
	dir := t.TempDir()
	src := `package sample

// generate:reset
type ResetableStruct struct {
	i     int
	str   string
	strP  *string
	s     []int
	m     map[string]string
	child *ResetableStruct
}
`
	require.NoError(t, os.WriteFile(filepath.Join(dir, "types.go"), []byte(src), 0o644))
	require.NoError(t, processDir(dir))

	got := readGenerated(t, dir)
	want := `// Code generated by cmd/reset; DO NOT EDIT.

package sample

// Reset zeroes the receiver struct fields back to their initial values.
func (rs *ResetableStruct) Reset() {
	if rs == nil {
		return
	}

	rs.i = 0
	rs.str = ""
	if rs.strP != nil {
		*rs.strP = ""
	}
	rs.s = rs.s[:0]
	clear(rs.m)
	if rs.child != nil {
		rs.child.Reset()
	}
}`
	require.Equal(t, want, got)

	assertCompiles(t, dir)
}

func TestGenerate_NestedWithMarker(t *testing.T) {
	got := writePackage(t, `package sample

// generate:reset
type Outer struct {
	inner Inner
	ptr   *Inner
}

// generate:reset
type Inner struct {
	x int
}
`)
	want := `// Code generated by cmd/reset; DO NOT EDIT.

package sample

// Reset zeroes the receiver struct fields back to their initial values.
func (rs *Outer) Reset() {
	if rs == nil {
		return
	}

	rs.inner.Reset()
	if rs.ptr != nil {
		rs.ptr.Reset()
	}
}

// Reset zeroes the receiver struct fields back to their initial values.
func (rs *Inner) Reset() {
	if rs == nil {
		return
	}

	rs.x = 0
}`
	require.Equal(t, want, got)
}

